/**
 * Line icons drawn as SVG path data on a 24×24 grid (stroke only, like TradingView's toolbar), shared by the
 * DOM (`<app-icon>`) and the canvas (the icon stamps are painted with `Path2D` from the same strings).
 * Compose with the helpers below so anchor dots, arrow heads and dashes stay consistent across icons.
 */
const r2 = (n: number) => Math.round(n * 100) / 100;
const P = (...pts: number[][]) => 'M' + pts.map((p) => p.join(' ')).join('L');
const Z = (...pts: number[][]) => P(...pts) + 'Z';
const L = (x1: number, y1: number, x2: number, y2: number) => `M${x1} ${y1}L${x2} ${y2}`;
/** anchor dot (a small circle) */
const C = (x: number, y: number, r = 1.7) => `M${r2(x - r)} ${y}a${r} ${r} 0 1 0 ${r2(2 * r)} 0a${r} ${r} 0 1 0 ${r2(-2 * r)} 0`;
const R = (x: number, y: number, w: number, h: number) => `M${x} ${y}h${w}v${h}h${-w}z`;
/** arrow head at (x2, y2) for a line coming from (x1, y1) */
const H = (x1: number, y1: number, x2: number, y2: number, s = 4) => {
  const a = Math.atan2(y2 - y1, x2 - x1);
  const p = (d: number) => `${r2(x2 - s * Math.cos(a + d))} ${r2(y2 - s * Math.sin(a + d))}`;
  return `M${p(0.5)}L${x2} ${y2}L${p(-0.5)}`;
};
const ARROW = (x1: number, y1: number, x2: number, y2: number, s = 4) => L(x1, y1, x2, y2) + H(x1, y1, x2, y2, s);
/** dashed line */
const D = (x1: number, y1: number, x2: number, y2: number, n = 4) => {
  let s = '';
  for (let i = 0; i < n; i++) {
    const a = i / n, b = (i + 0.55) / n;
    s += L(r2(x1 + (x2 - x1) * a), r2(y1 + (y2 - y1) * a), r2(x1 + (x2 - x1) * b), r2(y1 + (y2 - y1) * b));
  }
  return s;
};
/** regular star */
const star = (cx: number, cy: number, ro: number, ri: number) =>
  Z(...Array.from({ length: 10 }, (_, i) => { const a = -Math.PI / 2 + (i * Math.PI) / 5; const r = i % 2 ? ri : ro; return [r2(cx + r * Math.cos(a)), r2(cy + r * Math.sin(a))]; }));
/** cog wheel */
const cog = (cx: number, cy: number) =>
  Z(...Array.from({ length: 24 }, (_, i) => { const a = (i * Math.PI) / 12; const r = Math.floor(i / 3) % 2 ? 6.6 : 9; return [r2(cx + r * Math.cos(a)), r2(cy + r * Math.sin(a))]; }));
/** candle: wick from y1 to y2, body from b1 to b2 */
const candle = (x: number, y1: number, y2: number, b1: number, b2: number) => L(x, y1, x, y2) + R(x - 1.8, b1, 3.6, b2 - b1);

